import Foundation

// MARK: - WorkflowStageKindValue

/// The kind of actor that performs a workflow stage.
enum WorkflowStageKindValue: String, Codable, Equatable {
    case agent
    case human
    case terminal
}

// MARK: - WorkflowStageDefinition

/// A single stage within a workflow pipeline.
struct WorkflowStageDefinition: Codable, Equatable, Identifiable {
    var id: String
    var name: String
    var kind: WorkflowStageKindValue
    /// Agent name for `.agent` kind stages; nil for human/terminal stages.
    var agentName: String?

    enum CodingKeys: String, CodingKey {
        case id
        case name
        case kind
        case agentName = "agent_name"
    }
}

// MARK: - WorkflowPipeline

/// A named sequence of workflow stages (e.g., the code review pipeline).
struct WorkflowPipeline: Codable, Equatable, Identifiable {
    var id: String
    var label: String
    var stages: [WorkflowStageDefinition]
}

// MARK: - AgentManifest

/// The top-level manifest decoded from `team-manifest.json`.
///
/// Generated by `generate_manifest.py` from the `.claude/` directory.
struct AgentManifest: Codable, Equatable {
    var agents: [AgentInfo]
    var commands: [CommandInfo]
    var skills: [SkillInfo]
    var rules: [RuleInfo]
    var directoryHealth: DirectoryHealth
    var generatedAt: String
    var workflowPipelines: [WorkflowPipeline]

    enum CodingKeys: String, CodingKey {
        case agents
        case commands
        case skills
        case rules
        case directoryHealth
        case generatedAt = "generated_at"
        case workflowPipelines = "workflow_pipelines"
    }

    /// Memberwise initializer for constructing an `AgentManifest` directly (e.g., in `ManifestService`).
    init(
        agents: [AgentInfo],
        commands: [CommandInfo],
        skills: [SkillInfo],
        rules: [RuleInfo],
        directoryHealth: DirectoryHealth,
        generatedAt: String,
        workflowPipelines: [WorkflowPipeline]
    ) {
        self.agents = agents
        self.commands = commands
        self.skills = skills
        self.rules = rules
        self.directoryHealth = directoryHealth
        self.generatedAt = generatedAt
        self.workflowPipelines = workflowPipelines
    }

    init(from decoder: Decoder) throws {
        let container = try decoder.container(keyedBy: CodingKeys.self)
        agents = try container.decode([AgentInfo].self, forKey: .agents)
        commands = try container.decode([CommandInfo].self, forKey: .commands)
        skills = try container.decode([SkillInfo].self, forKey: .skills)
        rules = try container.decode([RuleInfo].self, forKey: .rules)
        directoryHealth = try container.decode(DirectoryHealth.self, forKey: .directoryHealth)
        generatedAt = try container.decode(String.self, forKey: .generatedAt)
        workflowPipelines = (try? container.decodeIfPresent([WorkflowPipeline].self, forKey: .workflowPipelines)) ?? []
    }
}

// MARK: - AgentRoleCategory

/// Grouping category for sorting and displaying agents.
enum AgentRoleCategory: Int, Comparable {
    case coreTeam = 0
    case specialists = 1
    case security = 2

    static func < (lhs: AgentRoleCategory, rhs: AgentRoleCategory) -> Bool {
        lhs.rawValue < rhs.rawValue
    }
}

// MARK: - AgentInfo

/// Information about a single agent in the team manifest.
struct AgentInfo: Codable, Equatable, Identifiable {
    var id: String
    var name: String
    var model: String
    var description: String
    var skills: [String]
    var displayName: String?
    var initials: String?
    var mcpServers: [String]?
    var tools: [String]?
    var file: String?

    enum CodingKeys: String, CodingKey {
        case id
        case name
        case model
        case description
        case skills
        case displayName = "display_name"
        case initials
        case mcpServers = "mcp_servers"
        case tools
        case file
    }

    // MARK: - Computed Properties

    /// Display label derived from `displayName` or humanized `id`.
    ///
    /// Strips "-agent" suffix, splits on "-", capitalizes each component, and joins with spaces.
    var displayLabel: String {
        if let name = displayName, !name.isEmpty {
            return name
        }
        let stripped = id.hasSuffix("-agent") ? String(id.dropLast(6)) : id
        return stripped
            .split(separator: "-")
            .map { $0.capitalized }
            .joined(separator: " ")
    }

    /// Role category used for sorting agents in the roster.
    var roleCategory: AgentRoleCategory {
        let coreTeamIds: Set<String> = [
            "macos-developer-agent",
            "staff-engineer-agent",
            "qa-agent",
            "pm-agent",
            "build-engineer-agent"
        ]
        let securityIds: Set<String> = [
            "security-audit-agent",
            "security-reasoning-agent",
            "security-static-agent",
            "security-platform-agent"
        ]

        if coreTeamIds.contains(id) { return .coreTeam }
        if securityIds.contains(id) { return .security }
        return .specialists
    }

    /// Sort comparator: by roleCategory first, then displayLabel alphabetically.
    static let sortComparator: @Sendable (AgentInfo, AgentInfo) -> Bool = { lhs, rhs in
        if lhs.roleCategory != rhs.roleCategory {
            return lhs.roleCategory < rhs.roleCategory
        }
        return lhs.displayLabel < rhs.displayLabel
    }
}

// MARK: - CommandInfo

/// Information about a slash command available in the toolkit.
struct CommandInfo: Codable, Equatable, Identifiable {
    var id: String
    var name: String
    var description: String
}

// MARK: - SkillInfo

/// Information about a skill module in the toolkit.
struct SkillInfo: Codable, Equatable, Identifiable {
    var id: String
    var name: String
    var category: String
}

// MARK: - RuleInfo

/// Information about a rule file in the toolkit.
struct RuleInfo: Codable, Equatable, Identifiable {
    var id: String
    var name: String
    var scope: String
}

// MARK: - DirectoryHealth

/// Summary of toolkit directory contents for health reporting.
struct DirectoryHealth: Codable, Equatable {
    var agentCount: Int
    var commandCount: Int
    var skillCount: Int
    var ruleCount: Int

    enum CodingKeys: String, CodingKey {
        case agentCount = "agent_count"
        case commandCount = "command_count"
        case skillCount = "skill_count"
        case ruleCount = "rule_count"
    }
}

