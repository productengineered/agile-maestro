import CoreGraphics

extension CGFloat {

    // MARK: - Spacing Tokens

    /// 4pt — micro spacing, icon-to-label gaps
    static let spacing4: CGFloat = 4

    /// 8pt — tight spacing, compact padding
    static let spacing8: CGFloat = 8

    /// 12pt — compact element spacing
    static let spacing12: CGFloat = 12

    /// 16pt — standard content padding
    static let spacing16: CGFloat = 16

    /// 20pt — medium-large spacing
    static let spacing20: CGFloat = 20

    /// 24pt — major section spacing
    static let spacing24: CGFloat = 24

    /// 32pt — large section spacing
    static let spacing32: CGFloat = 32

    // MARK: - Corner Radius Tokens

    /// 6pt — small radius for pills, tags, badges
    static let cornerRadiusSmall: CGFloat = 6

    /// 8pt — medium radius for controls, inputs
    static let cornerRadiusMedium: CGFloat = 8

    /// 12pt — card radius for content containers
    static let cornerRadiusCard: CGFloat = 12

    /// 16pt — large radius for sheets, popovers
    static let cornerRadiusLarge: CGFloat = 16

    // MARK: - Icon Size Tokens

    /// 16pt — small icons, inline glyphs
    static let iconSizeSmall: CGFloat = 16

    /// 20pt — medium icons, toolbar items
    static let iconSizeMedium: CGFloat = 20

    /// 24pt — large icons, section headers
    static let iconSizeLarge: CGFloat = 24

    // MARK: - Font Size Tokens

    /// 11pt — caption, fine print
    static let fontSizeCaption: CGFloat = 11

    /// 12pt — small labels, metadata
    static let fontSizeSmall: CGFloat = 12

    /// 13pt — body text (macOS default)
    static let fontSizeBody: CGFloat = 13

    /// 15pt — subheadline
    static let fontSizeSubheadline: CGFloat = 15

    /// 17pt — headline
    static let fontSizeHeadline: CGFloat = 17
}
